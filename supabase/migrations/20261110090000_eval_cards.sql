-- Plan 009: generated evaluation cards, pooled WER split into S / D / I, hand re-scoring,
-- and the "counts toward evaluation" flag. Additive only: nothing is dropped, renamed or deleted,
-- and the plan 003 rows stay exactly as they are.
-- Apply in the Supabase SQL editor BEFORE starting a backend built from plan 009: that backend
-- refuses to start while these columns / the table are missing.

-- 1. Settings: does the next run count toward the evaluation (the admin's checkbox, on by default)?
alter table public.app_settings
  add column if not exists eval_counts boolean not null default true;

-- 2. One made-up identity card per participant (never a real resident). The next session claims the
--    oldest unclaimed one.
create table if not exists public.eval_cards (
  id                    integer generated by default as identity primary key,
  created_at            timestamptz not null default now(),
  created_by            integer references public.staff_users (id) on delete set null,
  round_no              integer,
  style                 varchar(2)  not null,
  card                  text        not null,          -- JSON: {answers: {field: {expected, read, parts?}}}
  claimed_by_session_id integer unique,
  claimed_at            timestamptz
);

-- 3. Sessions: the card it read, and whether it counts toward the evaluation.
alter table public.eval_sessions
  add column if not exists card_id integer references public.eval_cards (id) on delete set null,
  add column if not exists counts  boolean not null default true;

alter table public.eval_cards
  drop constraint if exists eval_cards_claimed_by_session_fkey;
alter table public.eval_cards
  add constraint eval_cards_claimed_by_session_fkey
  foreign key (claimed_by_session_id) references public.eval_sessions (id) on delete set null;

-- 4. Answers: the WER split, and an optional hand re-score from the saved audio.
alter table public.eval_answers
  add column if not exists s_errors        integer,
  add column if not exists d_errors        integer,
  add column if not exists i_errors        integer,
  add column if not exists hand_reference  text,
  add column if not exists hand_hypothesis text,
  add column if not exists hand_s          integer,
  add column if not exists hand_d          integer,
  add column if not exists hand_i          integer,
  add column if not exists hand_words      integer,
  add column if not exists hand_scored_at  timestamptz,
  add column if not exists hand_scored_by  integer references public.staff_users (id) on delete set null;

comment on table public.eval_cards is
  'Plan 009. Generated made-up identity cards (ground-truth transcripts). Never real resident data. Admin only (backend).';

create index if not exists eval_cards_unclaimed_idx on public.eval_cards (id) where claimed_by_session_id is null;

-- Closed to the Data API like every other CeduSync table: only the backend reads and writes it.
alter table public.eval_cards enable row level security;
revoke all on table public.eval_cards from anon, authenticated;
