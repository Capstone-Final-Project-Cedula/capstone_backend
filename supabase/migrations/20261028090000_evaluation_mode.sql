-- Plan 003: Evaluation mode. The system logs every voice interview (per try and per field) so
-- Chapter 4's accuracy, WER and timing come from the system itself. Admin-only to read.
-- Apply in the Supabase SQL editor BEFORE starting a backend built from plan 003: that backend
-- refuses to start while these columns / tables are missing.
-- Also create the PRIVATE storage bucket 'eval-audio' (Storage -> New bucket, public OFF).

-- 1. Settings: evaluation mode is ON by default; the current testing round tags every session.
alter table public.app_settings
  add column if not exists evaluation_mode      boolean     not null default true,
  add column if not exists eval_round_type      varchar(10) not null default 'practice'
    check (eval_round_type in ('practice', 'scripted', 'uat', 'live')),
  add column if not exists eval_round_condition varchar(10) not null default 'quiet'
    check (eval_round_condition in ('quiet', 'noisy')),
  add column if not exists eval_round_card_set  varchar(40),
  add column if not exists eval_round_no        integer     not null default 1;

-- 2. One row per logged interview. Only a participant code, never a name.
create table if not exists public.eval_sessions (
  id               integer generated by default as identity primary key,
  started_at       timestamptz not null default now(),
  ended_at         timestamptz,
  round_no         integer     not null default 1,
  round_type       varchar(10) not null check (round_type in ('practice', 'scripted', 'uat', 'live')),
  round_condition  varchar(10) not null check (round_condition in ('quiet', 'noisy')),
  card_set         varchar(40),
  participant_no   integer     not null,
  participant_code varchar(12) not null,
  card_no          integer,
  input_method     varchar(10) not null default 'voice',
  device           varchar(200),
  build_label      varchar(60),
  staff_user_id    integer references public.staff_users (id) on delete set null,
  outcome          varchar(10) not null default 'open' check (outcome in ('open', 'issued', 'abandoned')),
  issuance_id      integer references public.ctc_issuance (id) on delete set null,
  error_count      integer     not null default 0,
  app_seconds      double precision,
  qr_seconds       double precision,
  scored           boolean     not null default false,
  unique (round_no, participant_no)
);

-- 3. One row per try, plus one 'final' row per field when the session is scored.
create table if not exists public.eval_answers (
  id               integer generated by default as identity primary key,
  session_id       integer not null references public.eval_sessions (id) on delete cascade,
  created_at       timestamptz not null default now(),
  field            varchar(40) not null,
  step             varchar(10) not null,
  attempt_no       integer     not null default 1 check (attempt_no >= 0),
  try_id           varchar(40),
  engine           varchar(10),
  model            varchar(40),
  beam             integer,
  audio_ref        text,
  transcript       text,
  whisper_seconds  double precision,
  extracted_value  text,
  extract_ok       boolean,
  yes_no           varchar(10),
  expected_value   text,
  final_value      text,
  finished_in      varchar(12),
  spoken_tries     integer,
  spelled_tries    integer,
  skipped          boolean,
  correct_first    boolean,
  correct_ladder   boolean,
  correct_finished boolean,
  wer_errors       integer,
  wer_words        integer,
  seconds          double precision,
  unique (session_id, try_id)
);

create table if not exists public.security_events (
  id          integer generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  route       varchar(120) not null,
  kind        varchar(20)  not null
);

comment on table public.eval_sessions is
  'Plan 003. One logged interview. Participant code only, no name. Read by admins only (backend).';
comment on table public.eval_answers is
  'Plan 003. One row per try and one "final" row per field. Transcripts and values are real speech: erase with the admin "Delete evaluation audio now" button after the study.';
comment on table public.security_events is
  'Plan 003. Failed logins and 401/403 answers (time, route, kind). No passwords, no names.';

create index if not exists eval_sessions_started_at_idx on public.eval_sessions (started_at desc);
create index if not exists eval_answers_session_id_idx  on public.eval_answers (session_id);
create index if not exists eval_answers_field_step_idx  on public.eval_answers (field, step);
create index if not exists security_events_created_idx  on public.security_events (created_at desc);

-- Closed to the Data API like every other CeduSync table: only the backend reads and writes them.
alter table public.eval_sessions   enable row level security;
alter table public.eval_answers    enable row level security;
alter table public.security_events enable row level security;
revoke all on table public.eval_sessions   from anon, authenticated;
revoke all on table public.eval_answers    from anon, authenticated;
revoke all on table public.security_events from anon, authenticated;
