-- Plan 001.3: Records accountability.
-- 1. ctc_issuance.print_count: how many times the PDF was downloaded or printed
--    from Records. The first print (0 -> 1) is the original; every later one is
--    rebuilt with a "COPY / RE-PRINT" mark. The stored PDF is never changed.
-- 2. record_access_log: who listed, viewed, downloaded or printed CTC records.
-- Apply this BEFORE starting a backend built from plan 001.3: the backend reads
-- print_count, and create_all() does not add columns to an existing table.

alter table public.ctc_issuance
  add column if not exists print_count integer not null default 0;

create table if not exists public.record_access_log (
  id             integer generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  staff_user_id  integer references public.staff_users (id) on delete set null,
  action         varchar(20) not null
                 check (action in ('list', 'view', 'download', 'print')),
  issuance_id    integer references public.ctc_issuance (id) on delete set null,
  ctc_number     varchar(30),
  is_copy        boolean,
  search_text    text check (search_text is null or char_length(search_text) <= 200)
);

comment on table public.record_access_log is
  'Audit trail of admin access to CTC records (list / view / download / print). Written by the FastAPI backend.';

create index if not exists record_access_log_created_at_idx on public.record_access_log (created_at desc);
create index if not exists record_access_log_issuance_id_idx on public.record_access_log (issuance_id);

-- Closed to the Data API like every other CeduSync table: only the backend
-- (table owner) writes and reads it.
alter table public.record_access_log enable row level security;
revoke all on table public.record_access_log from anon, authenticated;
