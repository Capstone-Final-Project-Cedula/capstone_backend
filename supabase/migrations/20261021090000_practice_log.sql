-- Plan 001.7: TEMPORARY practice session log.
-- Every voice interview done for practice is logged answer by answer (what Whisper
-- heard, what the system made of it, what was finally saved, tries, seconds), so
-- Ralph can see where live use still goes wrong. Plan 003 (Evaluation mode)
-- replaces it. Written only while PRACTICE_LOG_ENABLED=True in the backend .env.
-- Apply this BEFORE turning PRACTICE_LOG_ENABLED on: with the log on, the backend
-- refuses to start until these tables exist. With the log off nothing needs them.
--
-- Rollback / removal: run supabase/practice_log_drop.sql (it drops exactly what is
-- created here), then restart the backend with PRACTICE_LOG_ENABLED off.

-- One row: whether new sessions count as practice ('test') or real use ('real').
create table if not exists public.practice_log_settings (
  id    integer primary key check (id = 1),
  mode  varchar(10) not null default 'test' check (mode in ('test', 'real'))
);
insert into public.practice_log_settings (id, mode) values (1, 'test')
  on conflict (id) do nothing;

create table if not exists public.practice_log_sessions (
  id             integer generated by default as identity primary key,
  started_at     timestamptz not null default now(),
  ended_at       timestamptz,
  build_label    varchar(60),
  backend_commit varchar(40),
  mode           varchar(10) not null check (mode in ('test', 'real')),
  staff_user_id  integer references public.staff_users (id) on delete set null,
  input_method   varchar(10) not null default 'voice',
  outcome        varchar(10) not null default 'open'
                 check (outcome in ('open', 'issued', 'abandoned')),
  issuance_id    integer references public.ctc_issuance (id) on delete set null
);

create table if not exists public.practice_log_answers (
  id                  integer generated by default as identity primary key,
  session_id          integer not null references public.practice_log_sessions (id) on delete cascade,
  created_at          timestamptz not null default now(),
  -- an interview question (surname, date, address_town, ...) or the joined 'address' summary
  field               varchar(40) not null,
  attempts            integer not null default 1 check (attempts >= 0),
  -- [{heard, engine, seconds, parsed, ok, reason}] one item per attempt
  attempt_details     jsonb not null default '[]'::jsonb,
  first_value         text,    -- first voice-parsed value, in the form the CTC saves
  accepted_value      text,    -- the value accepted during the interview
  accepted_engine     varchar(10) not null
                      check (accepted_engine in ('whisper', 'browser', 'typed', 'spelled', 'skipped')),
  seconds             double precision check (seconds is null or seconds >= 0),
  final_value         text,    -- filled when the CTC is issued
  changed_after_voice boolean, -- filled when the CTC is issued
  unique (session_id, field)
);

comment on table public.practice_log_sessions is
  'TEMPORARY (plan 001.7). One practice interview. Written by the FastAPI backend only while PRACTICE_LOG_ENABLED is on.';
comment on table public.practice_log_answers is
  'TEMPORARY (plan 001.7). One row per finished interview question. May contain real names typed or heard in practice.';
comment on table public.practice_log_settings is
  'TEMPORARY (plan 001.7). One row: mode test / real for new practice sessions.';

create index if not exists practice_log_sessions_started_at_idx on public.practice_log_sessions (started_at desc);
create index if not exists practice_log_answers_session_id_idx on public.practice_log_answers (session_id);

-- Closed to the Data API like every other CeduSync table: only the backend
-- (table owner) writes and reads them.
alter table public.practice_log_settings enable row level security;
alter table public.practice_log_sessions enable row level security;
alter table public.practice_log_answers enable row level security;
revoke all on table public.practice_log_settings from anon, authenticated;
revoke all on table public.practice_log_sessions from anon, authenticated;
revoke all on table public.practice_log_answers from anon, authenticated;
